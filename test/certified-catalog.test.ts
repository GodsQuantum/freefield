import { test } from "node:test";
import assert from "node:assert/strict";
import { certifiedCatalog } from "../server/certified-catalog.ts";
import { loadRegistry, repoRoot } from "../server/registry.ts";
const root = repoRoot(), { apps } = loadRegistry(root);
test("certified production catalog exposes exactly reviewed applications, not installed candidates", () => {
  const c = certifiedCatalog(root, apps);
  assert.equal(c.apps.length, 34);
  assert.equal(c.proofs.size, c.apps.length);
  assert.ok(c.proofs.has("character-swap"));
  assert.ok(c.proofs.has("talking"));
  assert.ok(c.proofs.has("voice-clone"));
  assert.ok(c.proofs.has("upscale-video-hd"));
  assert.ok(c.proofs.has("ltx25-q3-t2va-lite"));
  assert.ok(c.proofs.has("ltx25-q3-t2va-native-896"));
  const ltx=c.apps.find(a=>a.id==="ltx25-q3-t2va-native-896")!;
  assert.equal(ltx.graph!["ff_up"].class_type,"FreefieldLTXStatsUpscale");
  assert.equal(ltx.graph!["405:374"].class_type,"FreefieldSequentialVideoDecode");
  assert.ok(c.proofs.has("recast"));
  assert.ok(c.proofs.has("recast-animate-preview"));
  assert.ok(c.proofs.has("recast-animate-29f"));
  assert.ok(c.proofs.has("qwen21-edit-cfg1"));
  const recastLong=c.apps.find(a=>a.id==="recast-animate-29f")!;
  assert.equal(recastLong.graph!["ff_window"].inputs.frames,29);
  assert.equal(recastLong.graph!["ff_extend"].inputs.previous_frame_count,5);
  assert.deepEqual(recastLong.graph!["ff_extend"].inputs.previous_frames,["213:6",0]);
  assert.deepEqual(recastLong.graph!["ff_extend"].inputs.video_frame_offset,["213:114",3]);
  assert.equal(recastLong.graph!["ff_tail"].inputs.length,12);
  assert.equal(recastLong.graph!["ff_tail"].inputs.batch_index,5);
  assert.deepEqual(recastLong.inputs.find(i=>i.id==="seed")?.bind,[{node:"213:19",field:"noise_seed"},{node:"ff_sample2",field:"noise_seed"}]);
  const cfg1=c.apps.find(a=>a.id==="qwen21-edit-cfg1")!;
  assert.equal(cfg1.graph!["6"].class_type,"FreefieldQwen21SequentialCPU");
  assert.equal(cfg1.graph!["8"].inputs.cfg,1);
  assert.equal(c.apps.find(a=>a.id==="qwen21-edit")!.graph!["8"].inputs.cfg,8);
  assert.ok(!cfg1.inputs.some(i=>i.id==="negative_prompt"));
  assert.deepEqual(cfg1.inputs.find(i=>i.id==="resolution")?.options?.map(o=>o.value),[768]);
  assert.deepEqual(cfg1.models,c.apps.find(a=>a.id==="qwen21-edit")!.models);
  const animation=c.apps.find(a=>a.id==="recast-animate-preview")!;
  assert.deepEqual(animation.inputs.find(i=>i.id==="mode")?.options?.map(o=>o.value),[false]);
  assert.deepEqual(animation.inputs.find(i=>i.id==="width")?.options?.map(o=>o.value),[320]);
  assert.deepEqual(animation.inputs.find(i=>i.id==="height")?.options?.map(o=>o.value),[320]);
  assert.equal(animation.graph!["ff_window"].inputs.frames,17);
  assert.deepEqual(c.apps.find(a=>a.id==="recast")?.inputs.find(i=>i.id==="mode")?.options?.map(o=>o.value),[true]);
  for (const id of ["video", "video-t2v", "motion-transfer", "style-reference"]) assert.ok(!c.proofs.has(id), id);
  assert.equal(c.apps.find(a=>a.id==="moss-image")?.inputs.find(i=>i.id==="fast_mode")?.default,true);
  assert.equal(c.apps.find(a=>a.id==="styles")?.inputs.find(i=>i.id==="ultra_fast_mode")?.default,true);
});
test("explicit broader allowlist cannot expose unqualified apps; empty list fails closed", () => {
  assert.deepEqual(certifiedCatalog(root, apps, ["create-image","video","motion-transfer"]).apps.map(a=>a.id),["create-image"]);
  assert.throws(()=>certifiedCatalog(root, apps, ["video"]));
  assert.throws(()=>certifiedCatalog(root, apps, []));
});
test("workflow drift excludes a formerly certified recipe", () => {
  const altered = apps.map(a=>a.id==="create-image" ? {...a, workflowPath: apps.find(b=>b.id==="z-image")!.workflowPath}:a);
  const c=certifiedCatalog(root, altered);
  assert.ok(!c.proofs.has("create-image"));
  assert.equal(c.apps.length,33);
});
